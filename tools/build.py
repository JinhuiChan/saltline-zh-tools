"""Apply a local translation/optimization overlay; never download or ship the game."""
import argparse
import ast
import base64
import json
from pathlib import Path
import re
import warnings
import zlib

warnings.filterwarnings('ignore', category=SyntaxWarning)
ROOT = Path(__file__).resolve().parents[1]
CATALOG = json.loads((Path(__file__).with_name('translations.json')).read_text(encoding='utf-8'))
MARKER = '<!-- saltline-zh-tools: locally generated -->'
ATTRIBUTION = 'Original experiment: Felix Rieseberg. https://x.com/felixrieseberg/status/2119925633564463609'


def translate(text):
    literals = CATALOG['literals']
    decoded_literals = {
        re.sub(r'\\(?:u([0-9a-fA-F]{4})|x([0-9a-fA-F]{2}))',
               lambda match: chr(int(match.group(1) or match.group(2), 16)), key): value
        for key, value in literals.items()
    }
    for original, chinese in literals.items():
        text = text.replace('>' + original + '<', '>' + chinese + '<')
        text = text.replace('aria-label="' + original + '"', 'aria-label="' + chinese + '"')

    def literal(match):
        raw = match.group(0)
        if len(raw) > 500:
            return raw
        try:
            value = ast.literal_eval(raw)
        except (ValueError, SyntaxError):
            return raw
        return json.dumps(decoded_literals[value], ensure_ascii=False) if value in decoded_literals else raw

    text = re.sub(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', literal, text)
    for original, chinese in CATALOG['templates'].items():
        text = text.replace(original, chinese)
    for word in ['Move','Look','Fire','Aim','Reload','Cut relay','Jump','Sprint','Crouch','Pause']:
        text = text.replace('</kbd> ' + word + '</span>', '</kbd> ' + literals[word] + '</span>')
    return text.replace('name:"PAC-9 Longshore"', 'name:"PAC-9 港勤型"')


def validate_cache(cache):
    if not isinstance(cache, dict) or not 1 <= len(cache) <= 64:
        raise ValueError('Expected 1–64 material sets')
    total = 0
    for name, maps in cache.items():
        if not re.fullmatch(r'[a-zA-Z0-9_]+', name) or not isinstance(maps, dict) or set(maps) != {'albedo','orm','normal'}:
            raise ValueError('Invalid material set')
        sizes = set()
        for packed in maps.values():
            size = packed.get('size')
            if type(size) is not int or not 1 <= size <= 2048:
                raise ValueError('Invalid texture dimensions')
            sizes.add(size)
            expected = size * size * 4
            total += expected
            if total > 128 * 1024 * 1024:
                raise ValueError('Texture cache exceeds 128 MiB')
            try:
                compressed = base64.b64decode(packed['data'], validate=True)
                decoder = zlib.decompressobj()
                pixels = decoder.decompress(compressed, expected + 1)
                if len(pixels) != expected or not decoder.eof or decoder.unused_data:
                    raise ValueError('Invalid decompressed pixel count')
            except (KeyError, TypeError, zlib.error) as error:
                raise ValueError('Invalid compressed texture') from error
        if len(sizes) != 1:
            raise ValueError('Material map dimensions differ')


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError('Unsupported input build: expected patch anchor missing or ambiguous')
    return text.replace(old, new, 1)


def transform(text, cache=None):
    if MARKER in text:
        raise ValueError('Input is already generated by this tool; use the original HTML')
    if not all(marker in text for marker in ['SALTLINE_POST', 'window.__G=t', 'function Gg(i)', 'function hM(i)']):
        raise ValueError('Unrecognized Saltline build; input left unchanged')
    # Small compatibility anchors, not copies of upstream functions or shaders.
    text = replace_once(text, 'if(_){n.setPixelRatio(X),n.setSize(ie,F,!1);let re=ne*S.scale,', 'if(_){let re=ne*S.scale,')
    text = replace_once(text, 'ue>$&&(re*=Math.sqrt($/ue));let me=', 'ue>$&&(re*=Math.sqrt($/ue));n.setPixelRatio(X*re),n.setSize(ie,F,!1);let me=')
    text = text.replace('<link rel="stylesheet" href="https://fonts.googleapis.com/', '<link rel="preload" as="style" onload="this.onload=null;this.rel=\'stylesheet\'" href="https://fonts.googleapis.com/')
    if cache is not None:
        validate_cache(cache)
        payload = json.dumps(cache, separators=(',', ':'))
        text = replace_once(text, 'async function Gg(i){', 'const SL_BAKED_TEXTURES=' + payload + ';\nasync function Gg(i){')
        loader = (Path(__file__).with_name('cache-loader.js')).read_text(encoding='utf-8')
        text = replace_once(text, 'function A(O){let q=p.get(O);if(q)return q;', loader + '\nfunction A(O){let q=p.get(O);if(q)return q;if(cachedSets.has(O)){q=cachedSets.get(O);p.set(O,q);a.sets++;a.bytes+=q.size*q.size*4*1.34*3;return q;}')
    text = translate(text)
    text = text.replace("'Big Shoulders Display', 'Impact'", "'Big Shoulders Display', 'Microsoft YaHei', 'PingFang SC', 'Impact'")
    text = text.replace("'Barlow Condensed', 'Arial Narrow', system-ui", "'Barlow Condensed', 'Microsoft YaHei', 'PingFang SC', 'Arial Narrow', system-ui")
    text = text.replace("'IBM Plex Mono', ui-monospace", "'IBM Plex Mono', 'Microsoft YaHei', 'PingFang SC', ui-monospace")
    text = replace_once(text, '</style>', CATALOG['css'] + '</style>')
    # Credit follows every standalone output, even when separated from this repository.
    text = re.sub(r'(<p class="m-note">)[\s\S]*?(</p>)', r'\1原作：Felix Rieseberg · 非官方汉化与性能优化\2', text, count=1)
    license_text = (ROOT / 'licenses' / 'three-r180-MIT.txt').read_text(encoding='utf-8')
    notice = '\n<!--\n' + ATTRIBUTION + '\nOriginal game licensing is separate; this tool does not grant redistribution rights.\nBundled Three.js r180 license (Three.js only):\n' + license_text + '\n-->\n'
    if not re.search(r'<meta\s+charset=', text, re.I):
        text = '<meta charset="utf-8">\n' + text
    if re.search(r'<html\b', text, re.I):
        text = re.sub(r'<html\b[^>]*>', '<html lang="zh-CN">', text, count=1, flags=re.I)
    else:
        text = '<html lang="zh-CN">\n' + text + '\n</html>'
    text = re.sub(r'<!doctype[^>]*>', '', text, count=1, flags=re.I)
    return MARKER + notice + '<!doctype html>\n' + text


def write_output(source, destination, text, force=False):
    source, destination = Path(source), Path(destination)
    if source.resolve() == destination.resolve() or (destination.exists() and source.samefile(destination)):
        raise ValueError('The original file cannot be overwritten')
    if destination.exists() and not force:
        raise FileExistsError('Output exists; choose another path or pass --force')
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open('w' if force else 'x', encoding='utf-8', newline='\n') as output:
        output.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input', type=Path, help='Your legally obtained, compatible original HTML')
    parser.add_argument('output', type=Path, help='Local generated HTML; do not commit')
    parser.add_argument('--textures', type=Path, help='Optional locally baked texture JSON')
    parser.add_argument('--force', action='store_true', help='Replace an existing output, never the input')
    args = parser.parse_args()
    try:
        cache = json.loads(args.textures.read_text(encoding='utf-8')) if args.textures else None
        result = transform(args.input.read_text(encoding='utf-8-sig'), cache)
        write_output(args.input, args.output, result, args.force)
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + '\n')
    print('Generated local output:', args.output)


if __name__ == '__main__':
    main()
